// Run after npm ci and go mod download. Includes runtime dependency notices,
// without changing or guessing their copyright holders or license wording.
import { spawnSync } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const destination = join(root, 'third_party');
mkdirSync(destination, { recursive: true });
const moduleLines = [];
for (const platform of ['linux', 'windows']) {
  const modules = spawnSync('go', ['list', '-deps', '-f', '{{with .Module}}{{.Path}}|{{.Version}}|{{.Dir}}{{end}}', './cmd/amlens'], {
    cwd: join(root, 'backend'), encoding: 'utf8', env: { ...process.env, GOOS: platform, GOARCH: 'amd64', CGO_ENABLED: '0' },
  });
  if (modules.status !== 0) throw new Error(modules.stderr);
  moduleLines.push(...modules.stdout.split(/\r?\n/).filter(Boolean));
}
const entries = [];
for (const line of new Set(moduleLines)) {
  const [name, version, directory] = line.split('|');
  if (!version) continue;
  entries.push({ name, version, directory });
}
for (const name of ['react', 'react-dom', 'scheduler', 'cytoscape']) {
  const directory = join(root, 'frontend', 'node_modules', name);
  const { version } = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
  entries.push({ name, version, directory });
}
const index = ['# Dependency notices', '', 'Generated by scripts/collect-licenses.mjs from installed runtime dependencies.', '', '| Package | Version | Notices |', '|---|---|---|'];
for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
  const files = readdirSync(entry.directory, { withFileTypes: true }).filter((file) => file.isFile()
    && /^(license|copying|notice)([.-].*)?$/i.test(file.name) && !/\.(?:[cm]?js|ts|go)$/i.test(file.name));
  if (!files.length) throw new Error('No notice found for ' + entry.name);
  const links = files.map((file) => {
    const name = entry.name.replaceAll('/', '_') + '-' + file.name + '.txt';
    writeFileSync(join(destination, name), readFileSync(join(entry.directory, file.name)));
    return '[' + file.name + '](' + name + ')';
  });
  index.push('| ' + entry.name + ' | ' + entry.version + ' | ' + links.join(', ') + ' |');
}
const goRoot = spawnSync('go', ['env', 'GOROOT'], { encoding: 'utf8' });
if (goRoot.status !== 0) throw new Error('Cannot locate Go license');
writeFileSync(join(destination, 'Go-LICENSE.txt'), readFileSync(join(goRoot.stdout.trim(), 'LICENSE')));
index.push('', 'The compiled Go runtime: [Go license](Go-LICENSE.txt).', '');
writeFileSync(join(destination, 'README.md'), index.join('\n'));
console.log('Collected notices for ' + entries.length + ' runtime dependencies and Go.');
